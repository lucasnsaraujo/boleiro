"""Writes the outlines of Archivo's capitals and figures into `apps/desktop/ui/competitions/logoGlyphs.ts`.

The game draws a logo for every competition without a real one (apps/desktop/ui/competitions/generatedLogo.ts). A
logo's lettering is outlined, as a real logo's is, so it reads the same in any image, at any size, without the web
font: each glyph as an SVG path in font units (1,000 to the em, y down from the baseline) with its advance width, from
the vendored variable font (packages/design-tokens/fonts/Archivo.woff2, SIL OFL) at two instances: `heavy` for
wordmarks and figures, `narrow` for the lines under them.

Usage: .venv/bin/python pipeline/build_logo_glyphs.py
"""
from __future__ import annotations

import json
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "packages" / "design-tokens" / "fonts" / "Archivo.woff2"
OUT = ROOT / "apps" / "desktop" / "ui" / "competitions" / "logoGlyphs.ts"
CHARACTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZÁÀÂÃÄÉÈÊËÍÏÓÔÕÖÚÜÇÑ0123456789 .,-'&/·+"
# Weight and width of each instance: an expanded black for wordmarks, a condensed bold for the lines under them.
STYLES = {"heavy": {"wght": 860, "wdth": 118}, "narrow": {"wght": 700, "wdth": 72}}


def glyphs_of(location: dict[str, float]) -> dict[str, dict[str, object]]:
    font = instantiateVariableFont(TTFont(FONT), location)
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    found: dict[str, dict[str, object]] = {}
    for character in CHARACTERS:
        name = cmap[ord(character)]
        pen = SVGPathPen(glyph_set, ntos=lambda value: str(round(value)))
        glyph_set[name].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))
        found[character] = {"advance": round(font["hmtx"][name][0]), "d": pen.getCommands()}
    return found


def main() -> None:
    font = TTFont(FONT)
    lines = [
        "// Generated by pipeline/build_logo_glyphs.py from Archivo (SIL OFL); edit the script, not this file.",
        "",
        "/** A glyph's outline in font units, y down from the baseline, and how far it moves the pen. */",
        "export type Glyph = { advance: number; d: string };",
        "",
        "/** Archivo's capitals and figures, outlined at two instances. */",
        "export const LOGO_GLYPHS = {",
        f"  unitsPerEm: {font['head'].unitsPerEm},",
        f"  capHeight: {font['OS/2'].sCapHeight},",
    ]
    for style, location in STYLES.items():
        glyphs = glyphs_of(location)
        lines.append(f"  {style}: {{")
        for character, glyph in glyphs.items():
            lines.append(f"    {json.dumps(character, ensure_ascii=False)}: {{ advance: {glyph['advance']}, d: {json.dumps(glyph['d'])} }},")
        lines.append("  } as Record<string, Glyph>,")
    lines += ["};", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {OUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
